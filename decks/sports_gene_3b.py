def colloc(item, pl, en, examples, ctype, note="", extra=""):
    return [item, colloc_translation(pl, en, note), examples_block(examples, "example"), ctype,
            f"fce collocations {ctype} {T} {extra}".strip()]


def gf(sentence, answer, why, rule=None, tip=None, extra=""):
    return [*gap_fill_fields(sentence, answer, why, rule, tip), "gap-fill",
            f"fce use-of-english gap-fill {T} {extra}".strip()]


def oc(sentence, answer, why, rule=None, tip=None, extra=""):
    return [*open_cloze_fields(sentence, answer, why, rule, tip), "open-cloze",
            f"fce use-of-english open-cloze {T} {extra}".strip()]


