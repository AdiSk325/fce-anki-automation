def gr(rule, formula, usage, signals, tip, examples, mistakes, tags=""):
    return [rule, grammar_explanation(formula, usage, tip, signal=signals,
                                      signal_label="🔑 Słowa sygnałowe:"),
            examples_block(examples), mistakes_block(mistakes),
            f"fce grammar {T} {tags}".strip()]


def colloc(item, pl, en, examples, ctype, note="", extra=""):
    return [item, colloc_translation(pl, en, note), examples_block(examples, "example"), ctype,
            f"fce collocations {ctype} {T} {extra}".strip()]


def gf(sentence, answer, why, rule=None, tip=None, extra=""):
    return [*gap_fill_fields(sentence, answer, why, rule, tip), "gap-fill",
            f"fce use-of-english gap-fill {T} {extra}".strip()]


def oc(sentence, answer, why, rule=None, tip=None, extra=""):
    return [*open_cloze_fields(sentence, answer, why, rule, tip), "open-cloze",
            f"fce use-of-english open-cloze {T} {extra}".strip()]


def ch(sentence, options, answer, why, rule=None, tip=None, extra=""):
    return [*choice_fields(sentence, options, answer, why, rule, tip), "tense-choice",
            f"fce use-of-english tense-choice {T} {extra}".strip()]


def kwt(original, keyword, answer, full, why, rule, tip, extra=""):
    return [*kwt_fields(original, keyword, KG, answer, full, why, rule, tip),
            "key-word-transformation",
            f"fce use-of-english key-word-transformation {T} {extra}".strip()]


def tr(pl, hint, answer, alt, expl, wrong, extra=""):
    return [*translation_fields(pl, hint, answer, alt, expl, wrong), "translation",
            f"fce use-of-english translation {T} {extra}".strip()]


def pr(prompt, structure, models, why, extra=""):
    return [*production_fields(prompt, structure, models, why), "production",
            f"fce use-of-english production speaking-drill {T} {extra}".strip()]


